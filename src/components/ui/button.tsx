type ButtonVariantProps = Parameters<typeof buttonVariantsBase>[0]

// Merged with cn, so a className passed here (e.g. on a Link) overrides the
// variant's height, padding, or border instead of depending on CSS order.
function buttonVariants(props?: ButtonVariantProps) {
  return cn(buttonVariantsBase(props))
}

function Button({
  className,
  variant = "default",
  size = "default",
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariantsBase>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  )
}

export { Button, buttonVariants }
